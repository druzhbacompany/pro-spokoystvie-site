/**
 * Контракт каталога лабораторных исследований: типы, форматирование и
 * обязательные формулировки о цене/сроке.
 *
 * ВАЖНО: этот модуль не импортирует JSON-выгрузку и потому безопасен для
 * клиентских компонентов. Сами данные живут в lib/analyses-data.ts, который
 * тянет за собой ~578 КБ JSON и должен импортироваться ТОЛЬКО с сервера.
 *
 * Клиника «ПРО спокойствие» — точка приёма биоматериала: мы принимаем
 * биоматериал по записи и передаём его в партнёрскую лабораторию Хеликс.
 * Поэтому цена из каталога — СПРАВОЧНАЯ величина, а не окончательная цена
 * клиники, и каждое её отображение обязано сопровождаться PRICE_HINT.
 */

export type AnalysisType = "analysis" | "complex";

export type CatalogItem = {
  /** Код позиции в каталоге лаборатории, напр. «02-011». */
  code: string;
  title: string;
  type: AnalysisType;
  /** Справочная цена по каталогу лаборатории, ₽. Не окончательная. */
  price: number;
  /** Короткий срок («До 4 суток»); общая оговорка вынесена в TERM_NOTE. */
  term: string;
};

/** Общая оговорка к сроку выполнения (вынесена из каждой карточки). */
export const TERM_NOTE =
  "Указанный срок не включает день взятия биоматериала и уточняется при записи.";

/** Пояснение к цене. Обязательно рядом с каждой ценой. */
export const PRICE_HINT = "Итоговая стоимость уточняется при записи";

/** Неразрывные пробелы вместо Intl — исключает расхождение SSR/клиента. */
export function formatPrice(value: number): string {
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/g, " ");
}
